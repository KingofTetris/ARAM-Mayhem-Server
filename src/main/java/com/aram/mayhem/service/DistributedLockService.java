package com.aram.mayhem.service;

import java.util.function.Supplier;

/**
 * 分布式锁服务接口 —— 防止多台服务器同时执行同一任务的"排队系统"
 *
 * ═══════════════════════════════════════════════════════════════════
 * 一、这个接口是干什么的？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 这个接口提供了分布式锁功能，用于在多台服务器（或多个进程）环境下，
 * 确保同一时刻只有一个服务器能执行某个关键任务。
 *
 * 打个比方：
 * - 没有分布式锁 = 多个收银员同时卖同一张电影票（超卖问题）
 * - 有分布式锁 = 只有一个收银员能操作售票系统（安全）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 二、为什么需要分布式锁？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 在本项目中的典型场景：数据同步定时任务
 * - 如果部署了3台服务器，每台都会运行定时任务
 * - 没有锁 → 3台服务器同时同步数据，造成数据重复写入
 * - 有锁 → 只有第一台获取锁的服务器执行同步，其他服务器跳过
 *
 * ═══════════════════════════════════════════════════════════════════
 * 三、实现原理（基于 Redis SETNX）
 * ═══════════════════════════════════════════════════════════════════
 *
 * Redis 的 SETNX 命令（SET if Not eXists）：
 * - 如果key不存在 → 设置成功，返回true（获取锁成功）
 * - 如果key已存在 → 设置失败，返回false（锁被别人持有）
 *
 * 加锁流程：
 *   SETNX lock:data-sync <UUID> EX <TTL毫秒>
 *   ├── 成功 → 获取锁，执行任务
 *   └── 失败 → 锁被占用，跳过或等待
 *
 * 解锁流程（Lua脚本保证原子性）：
 *   if redis.call('get', KEYS[1]) == ARGV[1] then
 *       return redis.call('del', KEYS[1])
 *   else
 *       return 0
 *   end
 *
 * 为什么要用 Lua 脚本？
 * 因为"先检查值再删除"不是原子操作，可能被其他进程抢先删除。
 * Lua 脚本在 Redis 中是原子执行的，不会被中断。
 *
 * ═══════════════════════════════════════════════════════════════════
 * 四、本接口提供的方法一览
 * ═══════════════════════════════════════════════════════════════════
 *
 * 方法名                    | 功能说明
 * --------------------------|------------------------------------------
 * tryLock()                 | 尝试获取锁（非阻塞，获取失败立即返回false）
 * unlock()                  | 释放锁
 * executeWithLock(Supplier) | 获取锁后执行有返回值的任务
 * executeWithLock(Runnable) | 获取锁后执行无返回值的任务
 *
 * ═══════════════════════════════════════════════════════════════════
 * 五、实现类
 * ═══════════════════════════════════════════════════════════════════
 *
 * @see com.aram.mayhem.service.impl.DistributedLockServiceImpl 分布式锁服务实现类
 */
public interface DistributedLockService {

    /**
     * 尝试获取分布式锁 —— 非阻塞方式
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 尝试获取指定key的分布式锁。如果锁已被其他进程持有，立即返回false，
     * 不会等待锁释放（非阻塞）。
     *
     * 【锁的TTL（生存时间）】
     * 每个锁都有一个过期时间，防止持锁进程崩溃后锁永远不释放。
     * 例如：TTL=60秒，即使持锁进程崩溃，60秒后锁也会自动释放。
     *
     * @param lockKey 锁的标识key（如"data-sync"表示数据同步任务的锁）
     *                实际存储的key会加上前缀 "lock:"，如 "lock:data-sync"
     * @param ttlMs   锁的过期时间（毫秒），如60000表示60秒后自动释放
     * @return true=获取锁成功，false=锁已被其他进程持有
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 尝试获取数据同步锁，60秒后自动过期
     * boolean acquired = lockService.tryLock("data-sync", 60000);
     * if (acquired) {
     *     try {
     *         // 执行同步任务
     *         syncData();
     *     } finally {
     *         // 任务完成后释放锁
     *         lockService.unlock("data-sync");
     *     }
     * } else {
     *     // 锁被其他服务器持有，跳过本次同步
     *     log.info("数据同步任务正在其他服务器执行，跳过");
     * }
     */
    boolean tryLock(String lockKey, long ttlMs);

    /**
     * 释放分布式锁 —— 删除Redis中的锁key
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 释放之前获取的分布式锁。使用 Lua 脚本确保"检查值+删除"的原子性。
     *
     * 【安全释放机制】
     * 释放锁时会检查锁的值是否是自己设置的UUID：
     * - 如果是 → 说明锁还是自己持有的，安全删除
     * - 如果不是 → 说明锁已经过期并被其他进程获取，不删除（避免误删别人的锁）
     *
     * @param lockKey 锁的标识key（与tryLock传入的key一致）
     */
    void unlock(String lockKey);

    /**
     * 在分布式锁保护下执行有返回值的任务 —— 便捷方法
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 这是一个便捷方法，封装了"获取锁→执行任务→释放锁"的完整流程。
     * 无论任务成功还是抛出异常，锁都会在finally块中被释放。
     *
     * 【执行流程】
     * 1. tryLock(lockKey, ttlMs) → 尝试获取锁
     * 2. 如果获取失败 → 抛出 IllegalStateException
     * 3. 如果获取成功 → 执行 task.get()
     * 4. finally → unlock(lockKey) 释放锁
     *
     * @param lockKey 锁的标识key
     * @param ttlMs   锁的过期时间（毫秒）
     * @param task    要执行的任务（Supplier<T>，有返回值）
     * @param <T>     返回值类型
     * @return T 任务的执行结果
     * @throws IllegalStateException 获取锁失败时抛出
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 在锁保护下执行数据同步，返回同步的记录数
     * int syncedCount = lockService.executeWithLock("data-sync", 60000, () -> {
     *     return dataAggregatorService.aggregateAndSaveHeroData("14.1.1").size();
     * });
     */
    <T> T executeWithLock(String lockKey, long ttlMs, Supplier<T> task);

    /**
     * 在分布式锁保护下执行无返回值的任务 —— 便捷方法
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 与上面的 executeWithLock(Supplier) 类似，但任务没有返回值（Runnable）。
     * 内部实现是将 Runnable 包装成 Supplier，调用有返回值的版本。
     *
     * @param lockKey 锁的标识key
     * @param ttlMs   锁的过期时间（毫秒）
     * @param task    要执行的任务（Runnable，无返回值）
     * @throws IllegalStateException 获取锁失败时抛出
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 在锁保护下执行缓存预热
     * lockService.executeWithLock("cache-warmup", 120000, () -> {
     *     cacheWarmupService.warmupHeroCache(20);
     *     cacheWarmupService.warmupAugmentCache();
     * });
     */
    void executeWithLock(String lockKey, long ttlMs, Runnable task);
}
