package com.aram.mayhem.service;

import com.aram.mayhem.dto.UpdateProfileRequest;
import com.aram.mayhem.dto.UserProfileVO;

/**
 * 用户服务接口 —— 个人中心模块的"业务规则说明书"
 *
 * ═══════════════════════════════════════════════════════════════════
 * 一、这个接口是干什么的？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 这个接口定义了"个人中心模块"所有对外提供的业务功能。
 * 主要负责用户资料的查询和更新。
 *
 * 打个比方：
 * - 用户资料 = 个人名片（昵称、头像、偏好设置等）
 * - 部分更新 = 只改名片上需要改的部分，不用重新写整张名片
 *
 * ═══════════════════════════════════════════════════════════════════
 * 二、本接口提供的方法一览
 * ═══════════════════════════════════════════════════════════════════
 *
 * 方法名              | 功能说明                      | 是否需要登录
 * --------------------|------------------------------|------------
 * getUserProfile()    | 查看用户资料                  | 是
 * updateProfile()     | 修改用户资料（部分更新）       | 是
 *
 * ═══════════════════════════════════════════════════════════════════
 * 三、部分更新策略说明
 * ═══════════════════════════════════════════════════════════════════
 *
 * updateProfile() 采用"部分更新"策略：
 * - 请求中只传需要修改的字段
 * - 传null的字段不会被更新（保持原值不变）
 * - 这样用户只想改昵称时，不需要把头像、通知设置等都传一遍
 *
 * 例如：只想改昵称
 *   request.setNickname("新昵称");
 *   request.setAvatarUrl(null);          // null = 不改头像
 *   request.setDisplayMode(null);        // null = 不改显示模式
 *   request.setNotificationEnabled(null); // null = 不改通知设置
 *
 * ═══════════════════════════════════════════════════════════════════
 * 四、实现类
 * ═══════════════════════════════════════════════════════════════════
 *
 * @see com.aram.mayhem.service.impl.UserServiceImpl 用户服务实现类
 */
public interface UserService {

    /**
     * 获取用户资料 —— 查看用户的个人信息
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 根据用户ID获取完整的个人资料信息，包括：
     * - 基本信息：邮箱、昵称、头像URL
     * - 偏好设置：显示模式（0=默认/1=暗黑）、通知开关（0=关/1=开）
     * - 统计数据：发布的攻略数量、收藏数量
     * - 角色信息：用户角色（USER/ADMIN）
     *
     * @param userId 用户ID（从JWT Token中获取）
     * @return UserProfileVO 用户资料视图对象
     * @throws com.aram.mayhem.common.BusinessException 用户不存在时抛出404错误
     */
    UserProfileVO getUserProfile(Long userId);

    /**
     * 更新用户资料 —— 修改个人信息（部分更新）
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 采用"部分更新"策略，只更新请求中非null的字段。
     *
     * 【可更新字段】
     * - nickname → 昵称
     * - avatarUrl → 头像URL
     * - displayMode → 显示模式（0=默认/1=暗黑）
     * - notificationEnabled → 通知开关（0=关/1=开）
     *
     * 【不可更新字段】
     * - email → 邮箱不可修改（涉及登录凭证）
     * - role → 角色不可自行修改（需管理员操作）
     * - password → 密码修改需走专门的修改密码接口
     *
     * @param userId  用户ID（从JWT Token中获取）
     * @param request 更新请求体（仅包含需要修改的字段，null字段不更新）
     * @return UserProfileVO 更新后的用户资料
     * @throws com.aram.mayhem.common.BusinessException 用户不存在时抛出404错误
     */
    UserProfileVO updateProfile(Long userId, UpdateProfileRequest request);
}
