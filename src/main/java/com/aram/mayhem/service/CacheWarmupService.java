package com.aram.mayhem.service;

import com.aram.mayhem.dto.AugmentListVO;
import com.aram.mayhem.dto.HeroDetailVO;
import com.aram.mayhem.dto.HeroListVO;
import com.aram.mayhem.dto.PageResult;

import java.util.List;

/**
 * 缓存预热服务接口 —— 系统启动时的"提前烧水"服务
 *
 * ═══════════════════════════════════════════════════════════════════
 * 一、这个接口是干什么的？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 这个接口负责在系统启动时或定时任务中，提前把热点数据加载到 Redis 缓存中。
 * 这样用户第一次访问时就能直接从缓存获取数据，而不需要等待数据库查询。
 *
 * 打个比方：
 * - 没有缓存预热 = 客人点菜后才开始洗菜切菜（第一次访问慢）
 * - 有缓存预热 = 提前把常用食材准备好（第一次访问也快）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 二、本接口提供的方法一览
 * ═══════════════════════════════════════════════════════════════════
 *
 * 方法名                  | 功能说明                      | 调用时机
 * ------------------------|------------------------------|------------
 * warmupHeroCache()       | 预热英雄详情缓存              | 系统启动/定时任务
 * warmupAugmentCache()    | 预热符文列表缓存              | 系统启动/定时任务
 * warmupHeroListCache()   | 预热英雄列表缓存              | 系统启动/定时任务
 * cleanupStaleCache()     | 清理过期/无效缓存             | 定时任务
 *
 * ═══════════════════════════════════════════════════════════════════
 * 三、缓存策略说明
 * ═══════════════════════════════════════════════════════════════════
 *
 * 【英雄详情缓存】
 * - 缓存key：heroDetail::{英雄ID}
 * - 缓存时间：6小时
 * - 预热策略：按胜率排序取前N个英雄，提前加载它们的详情
 *
 * 【符文列表缓存】
 * - 缓存key：augment:list:{quality}:{synergySet}:{page}:{size}
 * - 缓存时间：30分钟
 * - 预热策略：分页加载所有符文，每页200条
 *
 * 【英雄列表缓存】
 * - 缓存key：hero:list:all
 * - 缓存时间：6小时
 * - 预热策略：加载所有英雄的列表数据
 *
 * ═══════════════════════════════════════════════════════════════════
 * 四、实现类
 * ═══════════════════════════════════════════════════════════════════
 *
 * @see com.aram.mayhem.service.impl.CacheWarmupServiceImpl 缓存预热服务实现类
 */
public interface CacheWarmupService {

    /**
     * 预热英雄详情缓存 —— 提前加载热门英雄的详情数据到Redis
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 按胜率排序取前N个英雄，调用 HeroService.getHeroDetail() 加载它们的详情。
     * 因为 getHeroDetail() 有 @Cacheable 注解，调用后数据会自动缓存到 Redis。
     *
     * 【预热流程】
     * 1. 查询数据库，按胜率排序取前N个英雄
     * 2. 逐个调用 heroService.getHeroDetail(id)
     * 3. 每次调用后，@Cacheable 自动将结果写入 Redis
     * 4. 记录成功和失败的数量
     *
     * @param topN 预热前N个英雄（如传10表示预热胜率最高的10个英雄）
     * @return List<Long> 成功预热的英雄ID列表
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 预热胜率最高的20个英雄
     * List<Long> warmedIds = cacheWarmupService.warmupHeroCache(20);
     * System.out.println("预热了 " + warmedIds.size() + " 个英雄");
     */
    List<Long> warmupHeroCache(int topN);

    /**
     * 预热符文列表缓存 —— 提前加载所有符文的列表数据到Redis
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 分页加载所有符文数据，每页200条，将结果写入 Redis 缓存。
     * 这样用户浏览符文列表时可以直接从缓存获取，不需要查数据库。
     *
     * @return int 成功预热的符文总数
     */
    int warmupAugmentCache();

    /**
     * 预热英雄列表缓存 —— 提前加载所有英雄的列表数据到Redis
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 加载所有英雄的列表数据（按胜率排序），将整个列表写入 Redis。
     * 缓存key为 "hero:list:all"，缓存时间6小时。
     *
     * @return int 成功预热的英雄总数
     */
    int warmupHeroListCache();

    /**
     * 清理过期/无效缓存 —— 删除数据库中已不存在的英雄的缓存数据
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 定期清理 Redis 中"脏数据"：
     * 1. 扫描所有 heroDetail::* 的缓存key
     * 2. 检查对应的英雄是否还存在于数据库
     * 3. 如果英雄已被删除，则删除对应的缓存
     * 4. 符文缓存的过期由 Redis TTL 自动管理
     *
     * @return int 清理的缓存条数
     */
    int cleanupStaleCache();
}
