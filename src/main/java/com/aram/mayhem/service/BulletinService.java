package com.aram.mayhem.service;

import com.aram.mayhem.dto.BulletinDetailVO;
import com.aram.mayhem.dto.BulletinListVO;
import com.aram.mayhem.dto.PageResult;

import java.util.List;

/**
 * 公告服务接口 —— 公告模块的"业务规则说明书"
 *
 * ═══════════════════════════════════════════════════════════════════
 * 一、这个接口是干什么的？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 这个接口定义了"公告模块"所有对外提供的业务功能。
 * 公告模块用于向用户展示系统通知、版本更新、活动信息等。
 *
 * 打个比方：
 * - 公告 = 游戏登录时弹出的通知横幅
 * - 置顶公告 = 置顶在公告列表最前面的重要通知
 * - 公告类型 = 不同类别的通知（版本更新、活动、普通通知）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 二、本接口提供的方法一览
 * ═══════════════════════════════════════════════════════════════════
 *
 * 方法名                  | 功能说明                      | 是否需要登录
 * ------------------------|------------------------------|------------
 * getBulletinList()       | 分页查询公告列表              | 否
 * getLatestBulletins()    | 获取最新N条公告               | 否
 * getBulletinDetail()     | 查看公告详情                  | 否
 *
 * ═══════════════════════════════════════════════════════════════════
 * 三、公告类型说明
 * ═══════════════════════════════════════════════════════════════════
 *
 * - version → 版本更新公告（如"v2.0版本更新说明"）
 * - event   → 活动公告（如"周末双倍经验活动"）
 * - notice  → 普通通知（如"服务器维护通知"）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 四、排序规则
 * ═══════════════════════════════════════════════════════════════════
 *
 * 公告列表的排序规则：
 * 1. 置顶公告排在最前面（isPinned=1 的公告优先显示）
 * 2. 非置顶公告按发布时间从新到旧排列
 *
 * ═══════════════════════════════════════════════════════════════════
 * 五、实现类
 * ═══════════════════════════════════════════════════════════════════
 *
 * @see com.aram.mayhem.service.impl.BulletinServiceImpl 公告服务实现类
 */
public interface BulletinService {

    /**
     * 获取公告列表 —— 公告模块的核心查询方法
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 分页查询公告列表，支持按类型筛选。
     * 排序规则：置顶公告优先，然后按发布时间倒序。
     *
     * @param type 公告类型筛选（可选，传null表示查看所有类型）
     *             可选值："version"（版本更新）、"event"（活动）、"notice"（通知）
     * @param page 页码，从1开始
     * @param size 每页数量
     * @return PageResult<BulletinListVO> 分页公告列表
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 获取所有类型的公告
     * PageResult<BulletinListVO> result = bulletinService.getBulletinList(null, 1, 10);
     *
     * // 只看版本更新公告
     * PageResult<BulletinListVO> result = bulletinService.getBulletinList("version", 1, 10);
     */
    PageResult<BulletinListVO> getBulletinList(String type, int page, int size);

    /**
     * 获取最新公告列表 —— 用于首页轮播展示
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 获取最新N条公告，通常用于App首页的公告轮播区域。
     * 排序规则与列表相同：置顶优先，然后按时间倒序。
     *
     * @param limit 返回数量上限（如传3则返回最新3条公告）
     * @return List<BulletinListVO> 最新公告列表
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 获取最新3条公告用于首页展示
     * List<BulletinListVO> latest = bulletinService.getLatestBulletins(3);
     */
    List<BulletinListVO> getLatestBulletins(int limit);

    /**
     * 获取公告详情 —— 查看公告的完整内容
     *
     * @param id 公告ID
     * @return BulletinDetailVO 公告详情
     * @throws com.aram.mayhem.common.BusinessException 公告不存在时抛出404错误
     */
    BulletinDetailVO getBulletinDetail(Long id);
}
