package com.aram.mayhem.service;

import com.aram.mayhem.dto.HeroDetailVO;
import com.aram.mayhem.dto.HeroListVO;
import com.aram.mayhem.dto.PageResult;

/**
 * 英雄服务接口 —— 英雄模块的"业务规则说明书"
 *
 * ═══════════════════════════════════════════════════════════════════
 * 一、这个接口是干什么的？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 这个接口定义了"英雄模块"所有对外提供的业务功能。
 * 它是 Controller 层和 Service 实现层之间的"合同"：
 * - Controller 只需要知道这个接口有哪些方法，不需要关心具体实现
 * - 实现类（HeroServiceImpl）负责具体的业务逻辑
 *
 * 打个比方：
 * - 这个接口 = 餐厅的菜单（告诉客人有哪些菜可以点）
 * - HeroServiceImpl = 后厨（真正做菜的地方）
 * - HeroController = 服务员（把客人的点单传给后厨）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 二、为什么要用接口而不是直接写实现类？
 * ═══════════════════════════════════════════════════════════════════
 *
 * 1. 解耦：Controller 依赖接口而非实现，更换实现不需要改 Controller
 * 2. 可测试：单元测试时可以用 Mock 对象替代真实实现
 * 3. 规范：接口定义了方法签名，团队协作时先定接口再写实现
 * 4. 扩展：未来可以有多种实现（如从不同数据源获取英雄数据）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 三、本接口提供的方法一览
 * ═══════════════════════════════════════════════════════════════════
 *
 * 方法名              | 功能说明                    | 返回类型
 * --------------------|----------------------------|---------------------------
 * getHeroList()       | 分页查询英雄列表            | PageResult<HeroListVO>
 * getHeroDetail()     | 查询单个英雄的详细信息       | HeroDetailVO
 *
 * ═══════════════════════════════════════════════════════════════════
 * 四、相关类关系图
 * ═══════════════════════════════════════════════════════════════════
 *
 *   HeroController（接收HTTP请求）
 *        │
 *        ▼ 调用
 *   HeroService（本接口，定义业务方法）
 *        │
 *        ▼ 实现
 *   HeroServiceImpl（具体业务逻辑，查询数据库+缓存）
 *        │
 *        ▼ 调用
 *   HeroMapper（数据库操作）
 *
 * ═══════════════════════════════════════════════════════════════════
 * 五、实现类
 * ═══════════════════════════════════════════════════════════════════
 *
 * @see com.aram.mayhem.service.impl.HeroServiceImpl 英雄服务实现类
 */
public interface HeroService {

    /**
     * 获取英雄列表 —— 英雄模块的核心查询方法
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 分页查询英雄列表，支持以下筛选和排序功能：
     *
     * 【搜索功能】
     * 输入关键词，可以同时匹配英雄的英文名、中文名、称号。
     * 例如：输入"盖伦"能搜到英雄"盖伦"，输入"Garen"也能搜到。
     *
     * 【梯级筛选】
     * 梯级代表英雄在 ARAM 模式中的强度等级，从强到弱为：
     *   S+（超模）> S（强势）> A（优秀）> B（一般）> C（弱势）
     * 选择某个梯级后，只显示该梯级的英雄。
     *
     * 【排序方式】
     * - winRate  → 按胜率从高到低排列（默认）
     * - pickRate → 按选取率从高到低排列
     * - tier     → 按梯级从强到弱排列
     * - name     → 按英文名从A到Z排列
     *
     * ═══════════════════════════════════════════════════════════════
     * 参数说明
     * ═══════════════════════════════════════════════════════════════
     *
     * @param page    页码，从1开始（第1页、第2页...）
     *                传1表示第一页，传2表示第二页
     *                如果传0或负数，实现类会自动修正为1
     *
     * @param size    每页显示的英雄数量
     *                传10表示每页10个英雄
     *                如果传0或负数，实现类会自动修正为10
     *
     * @param keyword 搜索关键词（可选，传null表示不搜索）
     *                匹配范围：英文名(nameEn)、中文名(nameZh)、称号(title)
     *                例如："盖伦"、"Garen"、"德玛西亚之力"都能匹配
     *
     * @param tier    梯级筛选（可选，传null表示不筛选梯级）
     *                可选值：S+、S、A、B、C
     *                例如：传"S+"只显示超模英雄
     *
     * @param sortBy  排序字段（可选，传null默认按胜率排序）
     *                可选值：winRate、pickRate、tier、name
     *                例如：传"pickRate"按选取率排序
     *
     * ═══════════════════════════════════════════════════════════════
     * 返回值说明
     * ═══════════════════════════════════════════════════════════════
     *
     * @return PageResult<HeroListVO> 分页结果对象，包含：
     *   - total   → 符合条件的英雄总数（用于计算总页数）
     *   - page    → 当前页码
     *   - size    → 每页数量
     *   - records → 当前页的英雄列表（HeroListVO对象列表）
     *
     * HeroListVO 包含的字段：
     *   id, nameEn, nameZh, title, role, tier, winRate, pickRate, imageUrl, isVersionTrap
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 获取第1页，每页10个英雄，不搜索不筛选，默认按胜率排序
     * PageResult<HeroListVO> result = heroService.getHeroList(1, 10, null, null, null);
     *
     * // 搜索"盖伦"，只看S+梯级，按选取率排序
     * PageResult<HeroListVO> result = heroService.getHeroList(1, 10, "盖伦", "S+", "pickRate");
     */
    PageResult<HeroListVO> getHeroList(int page, int size, String keyword, String tier, String sortBy);

    /**
     * 获取英雄详情 —— 查看单个英雄的完整信息
     *
     * ═══════════════════════════════════════════════════════════════
     * 功能说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 根据英雄ID获取该英雄的详细信息，包括：
     * - 基本信息：名称、称号、角色定位、梯级、胜率、选取率
     * - 战斗数据：平均击杀、平均死亡、平均助攻
     * - 技能列表：被动技能 + Q/W/E/R 四个主动技能
     * - 克制技巧：对抗该英雄的建议
     * - 协同英雄：与该英雄配合良好的英雄
     * - 推荐出装：该英雄的推荐装备方案
     * - 推荐符文：该英雄的推荐强化符文
     *
     * ═══════════════════════════════════════════════════════════════
     * 参数说明
     * ═══════════════════════════════════════════════════════════════
     *
     * @param id 英雄的唯一ID（数据库主键）
     *           可以从英雄列表接口返回的 HeroListVO.id 获取
     *           如果传入不存在的ID，实现类会抛出404异常
     *
     * ═══════════════════════════════════════════════════════════════
     * 返回值说明
     * ═══════════════════════════════════════════════════════════════
     *
     * @return HeroDetailVO 英雄详情对象，包含比列表更多的字段：
     *   - 继承 HeroListVO 的所有字段
     *   - description     → 英雄描述
     *   - avgKills        → 平均击杀数
     *   - avgDeaths       → 平均死亡数
     *   - avgAssists      → 平均助攻数
     *   - recommendedBuild → 推荐出装
     *   - recommendedAugments → 推荐符文列表（AugmentBriefVO）
     *   - skills          → 技能列表（SkillInfo）
     *   - counterTips     → 克制技巧列表
     *   - synergies       → 协同英雄列表
     *
     * ═══════════════════════════════════════════════════════════════
     * 缓存说明
     * ═══════════════════════════════════════════════════════════════
     *
     * 实现类使用了 @Cacheable 注解，查询结果会被缓存到 Redis：
     * - 缓存key：heroDetail::{英雄ID}
     * - 缓存时间：6小时
     * - 相同ID的重复查询会直接从缓存返回，不查数据库
     *
     * ═══════════════════════════════════════════════════════════════
     * 调用示例
     * ═══════════════════════════════════════════════════════════════
     *
     * // 获取ID为1的英雄详情
     * HeroDetailVO detail = heroService.getHeroDetail(1L);
     * System.out.println(detail.getNameZh());  // 输出英雄中文名
     * System.out.println(detail.getWinRate());  // 输出胜率
     */
    HeroDetailVO getHeroDetail(Long id);
}
